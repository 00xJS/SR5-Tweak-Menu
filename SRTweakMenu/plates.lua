local SEED, FLAGS, DIRTY = 0x38C, 0x3AC, 0x80000
function P.plate_seed(seed)
  local v = P.vehicle_object()
  if not v then return nil, "Get in a vehicle first" end
  local c = P.component(0x6A, v)
  if not c then return nil, "This vehicle has no plate" end
  if seed then
    wml.write_f32(c + SEED, seed)
    wml.write_u32(c + FLAGS, wml.read_u32(c + FLAGS) | DIRTY)
  end
  return wml.read_f32(c + SEED)
end
local function put(o)
  local _, why = P.plate_seed(o[3])
  return why or ("Plate " .. o[1] .. " on " .. o[2])
end
function P.plate_pick(o) return put(o) end
function P.plate_random() return put(P.PLATES_ALL[math.random(#P.PLATES_ALL)]) end
-- Your own plates: tools/plate_maker.py draws them into glyph row 0 of the atlas, which the game's own seeds never reach,
-- ships that in data\sr_boot\sr_boot_patch.vpp_pc (read at boot) and writes TweakMenu\custom_plates.txt, one plate a line:
-- TEXT|seed|background. Read when the menu loads.
function P.plates_custom()
  local out, f = {}, io.open(wml.root .. "\\custom_plates.txt", "r")
  if not f then return out end
  for line in f:lines() do
    local text, seed, bg = line:match("^([^|]+)|([^|]+)|([^|]*)")
    if text and tonumber(seed) then out[#out + 1] = { text:match("^%s*(.-)%s*$"), bg ~= "" and bg or "custom", tonumber(seed) } end
  end
  f:close()
  return out
end
function P.plate_custom(o)
  if not o then return "No custom plates yet: make them with tools\\plate_maker.py, then restart the game" end
  return put(o)
end
return P
